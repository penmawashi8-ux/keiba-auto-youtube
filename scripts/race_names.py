# 読み上げで読み間違えやすいもの
READ = {
    "NHKマイルカップ": "エヌエイチケイマイルカップ",
    "天皇賞（春）": "天皇賞、春",
    "天皇賞（秋）": "天皇賞、秋",
}
G1_NAMES = set(FULL)


def norm(name: str) -> str:
    """全角かっこ・空白・「GI」などの付記を除いた表記"""
    s = name.replace("（", "(").replace("）", ")").replace(" ", "").replace("　", "")
    for tag in ("(GI)", "(G1)", "(Ｇ１)", "(ＧⅠ)", "GI", "G1"):
        s = s.replace(tag, "")
    return s


def full_name(name: str) -> str:
    return FULL.get(norm(name), name)


def short_name(name: str) -> str:
    """サムネイルなどに大きく出す短い名前（netkeiba の表記のまま。全角かっこに）"""
    return norm(name).replace("(", "（").replace(")", "）")


def spoken(name: str) -> str:
    f = full_name(name)
    return READ.get(f, f)


def is_g1(name: str) -> bool:
    return norm(name) in G1_NAMES
